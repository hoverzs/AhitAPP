const LOG_PREFIX = "[generation-job]";

function jobLog(message: string, meta?: Record<string, unknown>): void {
  console.log(
    `${LOG_PREFIX} ${new Date().toISOString()} — ${message}`,
    meta ?? ""
  );
}

function jobWarn(message: string, meta?: Record<string, unknown>): void {
  console.warn(
    `${LOG_PREFIX} ${new Date().toISOString()} — ${message}`,
    meta ?? ""
  );
}

function jobError(message: string, meta?: Record<string, unknown>): void {
  console.error(
    `${LOG_PREFIX} ${new Date().toISOString()} — ${message}`,
    meta ?? ""
  );
}

export function isRetriableCronGenerationError(error: unknown): boolean {
  if (error instanceof GenerationSkippedError) return false;

  if (isGeminiOverloadError(error)) return true;

  const details = toGeminiErrorDetails(error);
  return (
    details.code === "GEMINI_OVERLOAD" ||
    details.code === "NETWORK" ||
    details.code === "TIMEOUT" ||
    details.code === "QUOTA" ||
    details.code === "MAX_TOKENS" ||
    details.code === "API_HTTP" ||
    details.code === "EMPTY_RESPONSE" ||
    details.code === "DUPLICATE_VERSE" ||
    details.code === "UNKNOWN"
  );
}

function resolveAttemptPhase(job: DailyGenerationJob): GenerationJobPhase {
  if (job.retry_count === 0) return "initial";
  return "hourly";
}

function appendLog(
  job: DailyGenerationJob,
  entry: Omit<GenerationAttemptLogEntry, "attemptNumber">
): void {
  const attemptNumber = job.retry_count + 1;
  job.logs.push({ ...entry, attemptNumber });
  job.retry_count = attemptNumber;
}

async function markJobPublished(
  job: DailyGenerationJob,
  publishedAt: string
): Promise<DailyGenerationJob> {
  job.status = "published";
  job.published_at = publishedAt;
  job.next_retry_at = null;
  job.last_error = null;
  job.last_error_code = null;
  await saveGenerationJob(job);
  return job;
}

async function markJobFailed(job: DailyGenerationJob): Promise<DailyGenerationJob> {
  job.status = "failed";
  job.next_retry_at = null;
  await saveGenerationJob(job);
  return job;
}

/** Idempotens: ha már van áhítat a napra, sikernek tekintjük. */
export async function ensureDevotionalNotAlreadyPublished(
  date: string,
  job: DailyGenerationJob | null
): Promise<{ skipped: true; job: DailyGenerationJob | null } | { skipped: false }> {
  const history = await readDevotionals();
  const existing = getDevotionalByDate(history, date);

  if (!existing) {
    return { skipped: false };
  }

  jobLog("Már létezik áhítat — duplikáció elkerülve", {
    date,
    title: existing.title,
  });

  if (job) {
    appendLog(job, {
      at: new Date().toISOString(),
      phase: resolveAttemptPhase(job),
      success: true,
      message: `Már publikálva: ${existing.date}`,
    });
    await markJobPublished(
      job,
      existing.generatedAt ?? existing.updatedAt ?? new Date().toISOString()
    );
    return { skipped: true, job };
  }

  return { skipped: true, job: null };
}

export interface GenerationAttemptResult {
  success: boolean;
  skipped?: boolean;
  /** A kihagyás oka (pl. jóváhagyott heti terv kezeli a napot). */
  skipReason?: string;
  /** A napot kezelő heti terv azonosítója. */
  managedByWeek?: string;
  /** A kezelt napnak még nincs jóváhagyott (nyilvános) áhítata — a heti műhelyben pótolni kell. */
  contentGap?: boolean;
  job: DailyGenerationJob;
  devotional?: Awaited<ReturnType<typeof autoGenerateDailyDevotional>>["devotional"];
  error?: string;
  code?: string;
}

/**
 * Ha a napot jóváhagyott heti terv kezeli, a napi automatikus generálás
 * kihagyja (nem versenyezhet a heti folyamattal). A kihagyás okát naplózza;
 * a függő napi feladatot lezárja, hogy ne induljon újrapróba. Ha a kezelt
 * napnak még nincs jóváhagyott áhítata, tartalmi hiányt jelez — hangosan,
 * hogy ne maradjon észrevétlen.
 */
async function skipIfManagedByWeeklyPlan(
  date: string,
  job: DailyGenerationJob,
  trigger: string
): Promise<GenerationAttemptResult | null> {
  const managing = await getManagingPlan(date);
  if (!managing) return null;

  const record = await readDevotionalRecord(date);
  const contentGap = !record || !isPublicStatus(record.status, record.weekId);
  const reason =
    `A(z) ${date} napot jóváhagyott heti terv kezeli (${managing.weekId}) — a napi automatikus generálás kihagyva.` +
    (contentGap
      ? " FIGYELEM: a napnak még nincs jóváhagyott áhítata a heti műhelyben — pótolni kell."
      : "");

  if (contentGap) {
    jobWarn(`TARTALMI HIÁNY KOCKÁZAT — ${reason}`, { date, trigger, weekId: managing.weekId });
  } else {
    jobLog(reason, { date, trigger, weekId: managing.weekId });
  }
  // A napi feladat lezárása: nincs értelme óránkénti újrapróbának, a nap nem az övé.
  await deleteGenerationJob(date);

  return {
    success: true,
    skipped: true,
    skipReason: reason,
    managedByWeek: managing.weekId,
    contentGap,
    job,
  };
}

/**
 * Egy generálási kísérlet — naplózás + job állapot frissítés.
 */
export async function runGenerationAttempt(
  date: string,
  options?: { trigger?: "cron" | "retry_processor" | "manual" }
): Promise<GenerationAttemptResult> {
  const trigger = options?.trigger ?? "cron";
  const job = (await getGenerationJob(date)) ?? createEmptyGenerationJob(date);

  const managed = await skipIfManagedByWeeklyPlan(date, job, trigger);
  if (managed) return managed;

  const idempotent = await ensureDevotionalNotAlreadyPublished(date, job);
  if (idempotent.skipped) {
    return {
      success: true,
      skipped: true,
      job: idempotent.job ?? job,
    };
  }

  if (job.status === "failed") {
    jobWarn("Feladat FAILED állapotban — kihagyva", { date, trigger });
    return { success: false, job, error: job.last_error ?? "Sikertelen generálás." };
  }

  if (job.status === "published") {
    return { success: true, skipped: true, job };
  }

  if (
    job.status === "pending_retry" &&
    job.next_retry_at &&
    new Date(job.next_retry_at).getTime() > Date.now() &&
    trigger !== "manual"
  ) {
    jobWarn("Következő retry még nem esedékes — kihagyva", {
      date,
      next_retry_at: job.next_retry_at,
      trigger,
    });
    return {
      success: false,
      job,
      error: job.last_error ?? "Várakozás a következő automatikus újrapróbára.",
    };
  }

  if (job.auto_retry_count >= MAX_AUTO_RETRIES && job.status === "pending_retry") {
    await markJobFailed(job);
    jobError("auto_retry_count elérte a maximumot — FAILED", {
      date,
      auto_retry_count: job.auto_retry_count,
    });
    return {
      success: false,
      job,
      error: job.last_error ?? "Három óránkénti újrapróba után sem sikerült.",
    };
  }

  job.status = "running";
  job.last_attempt_at = new Date().toISOString();
  await saveGenerationJob(job);

  const phase = resolveAttemptPhase(job);
  jobLog(`Generálás indult (${trigger}, ${phase})`, {
    date,
    retry_count: job.retry_count,
    auto_retry_count: job.auto_retry_count,
    next_retry_at: job.next_retry_at,
  });

  try {
    const result = await autoGenerateDailyDevotional(date, { forcePublished: true });
    const publishedAt = new Date().toISOString();

    appendLog(job, {
      at: publishedAt,
      phase,
      success: true,
      message: `Sikeres: ${result.devotional.date} — „${result.devotional.title}”`,
    });

    await markJobPublished(job, publishedAt);

    jobLog("Sikeres generálás és közzététel", {
      date,
      title: result.devotional.title,
      attempt: job.retry_count,
    });

    return {
      success: true,
      job,
      devotional: result.devotional,
    };
  } catch (error) {
    // Tárolóhiba (pl. Redis-korlát) nem Gemini-hiba: ne rögzítsük generálási
    // kísérletként, a hívó (route) tárolóhibaként jelezze.
    if (isAnyStorageError(error)) throw error;

    // A nap közben heti tervhez került: nem hiba, nem újrapróbálandó.
    if (error instanceof ManagedByWeeklyPlanError) {
      const reason = error.message;
      jobWarn(reason, { date, trigger });
      await deleteGenerationJob(date);
      return {
        success: true,
        skipped: true,
        skipReason: reason,
        managedByWeek: error.weekId,
        contentGap: true,
        job,
      };
    }

    if (error instanceof GenerationSkippedError) {
      const history = await readDevotionals();
      const existing = getDevotionalByDate(history, date);
      if (existing) {
        appendLog(job, {
          at: new Date().toISOString(),
          phase,
          success: true,
          message: error.reason,
        });
        await markJobPublished(
          job,
          existing.generatedAt ?? existing.updatedAt ?? new Date().toISOString()
        );
        return { success: true, skipped: true, job, devotional: existing };
      }
    }

    const details = toGeminiErrorDetails(error);

    appendLog(job, {
      at: new Date().toISOString(),
      phase,
      success: false,
      error: details.message,
      code: details.code,
    });

    job.last_error = details.message;
    job.last_error_code = details.code;
    job.last_attempt_at = new Date().toISOString();

    logGeminiError(error, `${LOG_PREFIX} ${date}`);
    jobError("Generálási kísérlet sikertelen", {
      date,
      attempt: job.retry_count,
      ...describeErrorForLog(error),
    });

    if (!isRetriableCronGenerationError(error)) {
      await markJobFailed(job);
      jobError("Nem újrapróbálható hiba — FAILED", {
        date,
        code: details.code,
      });
      return { success: false, job, error: details.message, code: details.code };
    }

    const nextAt = scheduleNextRetry(job);
    if (!nextAt) {
      await markJobFailed(job);
      jobError("Összes óránkénti retry kimerült — FAILED", {
        date,
        auto_retry_count: job.auto_retry_count,
      });
      return { success: false, job, error: details.message, code: details.code };
    }

    job.status = "pending_retry";
    job.next_retry_at = nextAt.toISOString();
    await saveGenerationJob(job);

    jobWarn("PENDING_RETRY — következő óránkénti próba ütemezve", {
      date,
      retry_count: job.retry_count,
      auto_retry_count: job.auto_retry_count,
      next_retry_at: job.next_retry_at,
    });

    return { success: false, job, error: details.message, code: details.code };
  }
}

export type ProcessDueRetriesResult =
  | { processed: false; reason: string }
  | GenerationAttemptResult;

/**
 * Esedékes retry feladat feldolgozása (mai nap) — idempotens.
 * Hobby plan: nincs gyakori Vercel cron; admin / külső hívás vagy napi cron elején.
 */
export async function processDueGenerationRetries(
  now = new Date()
): Promise<ProcessDueRetriesResult> {
  // Bekapcsolt autopilot mellett a régi óránkénti újrapróba nem fut (az autopilot átvette).
  if (await isAutopilotEnabled()) {
    return { processed: false, reason: "Az autopilot átvette a napi generálást." };
  }

  const date = getAppTodayIso(now);
  const job = await getGenerationJob(date);

  if (!job) {
    return { processed: false, reason: "Nincs aktív feladat a mai napra." };
  }

  const managed = await skipIfManagedByWeeklyPlan(date, job, "retry_processor");
  if (managed) return managed;

  const idempotent = await ensureDevotionalNotAlreadyPublished(date, job);
  if (idempotent.skipped) {
    return {
      success: true,
      skipped: true,
      job: idempotent.job ?? job,
    };
  }

  if (job.status === "published") {
    return { processed: false, reason: "A mai generálás már sikeres." };
  }

  if (job.status === "failed") {
    return { processed: false, reason: "A mai generálás véglegesen sikertelen (FAILED)." };
  }

  if (job.status !== "pending_retry") {
    return { processed: false, reason: "Nincs függőben lévő retry (pending_retry)." };
  }

  if (job.auto_retry_count >= MAX_AUTO_RETRIES) {
    await markJobFailed(job);
    return {
      processed: false,
      reason: `Elértük a maximum ${MAX_AUTO_RETRIES} óránkénti újrapróbát — FAILED.`,
    };
  }

  if (!job.next_retry_at) {
    return { processed: false, reason: "Hiányzó next_retry_at." };
  }

  if (new Date(job.next_retry_at).getTime() > now.getTime()) {
    return {
      processed: false,
      reason: `Következő retry: ${job.next_retry_at}`,
    };
  }

  jobLog("Ütemezett óránkénti retry indítása", {
    date,
    retry_count: job.retry_count,
    auto_retry_count: job.auto_retry_count,
    next_retry_at: job.next_retry_at,
  });

  return runGenerationAttempt(date, { trigger: "retry_processor" });
}
