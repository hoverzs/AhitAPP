export interface PublicDay {
  date: string;
  /** Közzétett áhítat erre a napra, vagy null (még nincs / nincs közzétéve). */
  devotional: Devotional | null;
}

export interface HomePageData {
  todayIso: string;
  /** Közzétett áhítatok az elmúlt 8 napból, újabb elöl. */
  devotionals: Devotional[];
  /** A főoldali (fő) áhítat: a mai, vagy ha még nincs, a legutóbbi. */
  latest: Devotional | null;
  /** A nyolcnapos dátumválasztó napjai, a mai elöl. */
  days: PublicDay[];
}

function buildPublicDays(todayIso: string, devotionals: Devotional[]): PublicDay[] {
  const byDate = new Map(devotionals.map((d) => [devotionalDateKey(d), d]));
  return getPublicWindowDates(todayIso).map((date) => ({
    date,
    devotional: byDate.get(date) ?? null,
  }));
}

const EMPTY_HOME = (): HomePageData => {
  const todayIso = getAppTodayIso();
  return {
    todayIso,
    devotionals: [],
    latest: null,
    days: buildPublicDays(todayIso, []),
  };
};

export async function loadHomePageData(): Promise<HomePageData> {
  try {
    const todayIso = getAppTodayIso();
    const devotionals = await getPublicWindowDevotionals();
    // A lista dátum szerint csökkenő: az első a mai, ha van, különben a legutóbbi.
    const latest = devotionals[0] ?? null;

    return {
      todayIso,
      devotionals,
      latest,
      days: buildPublicDays(todayIso, devotionals),
    };
  } catch (error) {
    console.error("[loadHomePageData]", error);
    return EMPTY_HOME();
  }
}

export async function loadSiteNavData(): Promise<{
  todayHref: string;
  publishedCount: number;
}> {
  try {
    const devotionals = await getPublicWindowDevotionals();
    const latest = devotionals[0];
    return {
      todayHref: latest ? `/nap/${latest.dayNumber}` : "/",
      publishedCount: devotionals.length,
    };
  } catch {
    return { todayHref: "/", publishedCount: 0 };
  }
}
export async function buildAdminDevotionalContext(
  devotionals: Devotional[]
): Promise<AdminDevotionalContext> {
  const target = resolveManualGenerationTarget(devotionals);
  const pending = devotionals
    .map(normalizeDevotional)
    .find((d) => isPendingReview(d.status));

  let reviewWarning: string | undefined;

  const truncatedPending = devotionals
    .map(normalizeDevotional)
    .find(
      (d) =>
        isPendingReview(d.status) &&
        d.lastApiError === TRUNCATED_DEVOTIONAL_REVIEW_MESSAGE
    );

  if (truncatedPending) {
    reviewWarning = TRUNCATED_DEVOTIONAL_REVIEW_MESSAGE;
  } else if (DEV_REVIEW_MODE && pending) {
    reviewWarning = `A mai áhítat még nincs jóváhagyva (${statusLabelHu(pending.status)}). Fejlesztői módban nem generálunk további napokat.`;
  }

  let todayGenerationJob = null;
  try {
    const today = getAppTodayIso();
    const job = await getGenerationJob(today);
    if (job) {
      todayGenerationJob = toAdminJobSummary(job);
    }
  } catch (error) {
    console.warn("[buildAdminDevotionalContext] generation job load failed:", error);
  }

  return {
    devReviewMode: DEV_REVIEW_MODE,
    autoGenerateDaily: AUTO_GENERATE_DAILY,
    autoPublishGenerated: AUTO_PUBLISH_GENERATED,
    cronEnabled: isCronGenerationEnabled(),
    promptVersion: PROMPT_VERSION,
    model: GEMINI_PLANNER_MODEL,
    generationTarget: {
      action: target.action,
      dayNumber: target.dayNumber,
      date: target.date,
      blockedReason: target.blockedReason,
    },
    reviewWarning,
    todayGenerationJob,
    externalRetryCron: {
      endpointUrl: getExternalRetryCronUrl(),
      scheduleLabel: EXTERNAL_RETRY_SCHEDULE_LABEL,
      helpText: EXTERNAL_RETRY_CRON_HELP,
    },
  };
}

export function toAdminListItems(devotionals: Devotional[]): AdminDevotionalListItem[] {
  return [...devotionals]
    .map(normalizeDevotional)
    .sort((a, b) => b.dayNumber - a.dayNumber)
    .map((d) => ({
      dayNumber: d.dayNumber,
      date: d.date,
      title: d.title,
      verse: d.verse,
      status: d.status,
      generatedAt: d.generatedAt,
      updatedAt: d.updatedAt,
      editedByAdmin: d.editedByAdmin,
      category: d.category,
    }));
}

export interface AdminPageData {
  memory: DevotionalMemory;
  latest: Devotional | null;
  reviewDevotional: Devotional | null;
  adminContext: AdminDevotionalContext;
  /** Teljes rekordok — „lusta" tárolónál csak az előnézetben megnyitott nap. */
  devotionals: Devotional[];
  listItems: AdminDevotionalListItem[];
  storageError: string | null;
  storageHint: string | null;
  /** A tárolóhiba oka (a cím és a magyarázat ebből készül), ha van hiba. */
  storageReason: StorageErrorReason | null;
  /** A tároló eredeti hibaüzenete (diagnosztikához). */
  storageDetail: string | null;
}

/**
 * „Lusta" admin (Blob): a lista és a generálási cél a könnyű index-sorokból
 * épül; teljes rekordot csak a megnyitandó (mai / függő / legutóbbi) napról
 * olvasunk, a többit az admin igény szerint tölti be.
 */
async function loadLazyAdminPageData(): Promise<AdminPageData> {
  const { entries, meta } = await readAdminEntries();
  const stubs = entries.map(entryToStub).map(normalizeDevotional);
  const todayIso = getAppTodayIso();

  const reviewDate =
    entries.find((e) => e.date === todayIso)?.date ??
    entries.find((e) => isPendingReview(e.status))?.date ??
    getLatestDevotional(stubs)?.date ??
    null;
  const reviewDevotional = reviewDate
    ? ((await getDevotionalStorage().getDevotionalByDate(reviewDate)) ?? null)
    : null;

  const target = resolveManualGenerationTarget(stubs);
  // A rekordok törlése után is megmaradó előzmény (meta) kiegészíti a csonkokét.
  const memory = mergeStoredMetaIntoMemory(
    buildDevotionalMemory(stubs, { nextDayNumber: target.dayNumber }),
    meta
  );

  return {
    memory,
    latest: reviewDevotional,
    reviewDevotional,
    adminContext: await buildAdminDevotionalContext(stubs),
    devotionals: reviewDevotional ? [reviewDevotional] : [],
    listItems: entries.map(entryToListItem),
    storageError: null,
    storageHint: null,
    storageReason: null,
    storageDetail: null,
  };
}

export async function loadAdminPageData(): Promise<AdminPageData> {
  let working: Awaited<ReturnType<typeof readAdminWorkingSet>>;
  let storageReason: StorageErrorReason | null = null;
  let storageDetail: string | null = null;
  try {
    if (isLazyAdminStorage()) {
      return await loadLazyAdminPageData();
    }
    working = await readAdminWorkingSet();
    if (working.storageError) storageReason = "not_configured";
  } catch (error) {
    console.error("[loadAdminPageData]", error);
    storageReason = storageErrorReason(error);
    storageDetail = error instanceof Error ? error.message : null;
    const info = describeStorageReasonHu(storageReason);
    working = {
      devotionals: [],
      storageError: info.message,
      storageHint: info.hint,
      driver: "redis",
    };
  }
  const { devotionals: raw, storageError, storageHint } = working;

  if (storageError) {
    const emptyCtx = await buildAdminDevotionalContext([]);
    return {
      memory: buildDevotionalMemory([]),
      latest: null,
      reviewDevotional: null,
      adminContext: emptyCtx,
      devotionals: [],
      listItems: [],
      storageError,
      storageHint,
      storageReason,
      storageDetail,
    };
  }

  try {
    const devotionals = raw.map(normalizeDevotional);

    // Az admin elsőként a mai áhítatot mutatja; ha még nincs, a függőben lévőt
    // (piszkozat / ellenőrzésre vár), végül a legutóbbit.
    const todayIso = getAppTodayIso();
    const reviewDevotional =
      devotionals.find((d) => d.date === todayIso) ??
      devotionals.find((d) => isPendingReview(d.status)) ??
      getLatestDevotional(devotionals);

    const memory = buildDevotionalMemory(raw, {
      nextDayNumber: resolveManualGenerationTarget(devotionals).dayNumber,
    });

    return {
      memory,
      latest: reviewDevotional,
      reviewDevotional,
      adminContext: await buildAdminDevotionalContext(devotionals),
      devotionals,
      listItems: toAdminListItems(devotionals),
      storageError: null,
      storageHint: null,
      storageReason: null,
      storageDetail: null,
    };
  } catch (error) {
    console.error("[loadAdminPageData]", error);
    const emptyCtx = await buildAdminDevotionalContext([]);
    return {
      memory: buildDevotionalMemory([]),
      latest: null,
      reviewDevotional: null,
      adminContext: emptyCtx,
      devotionals: [],
      listItems: [],
      storageError: "Nem sikerült betölteni az áhítatokat.",
      storageHint: error instanceof Error ? error.message : null,
      storageReason: "unknown",
      storageDetail: null,
    };
  }
}
