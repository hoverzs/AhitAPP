export type DevotionalStatus =
  | "draft"
  | "needs_review"
  | "approved"
  | "published";

/** Korábbi verzió pillanatkép (újragenerálás / AI finomítás backup) */
export interface DevotionalVersionSnapshot {
  savedAt: string;
  reason: "regenerate" | "manual_backup" | "ai_iteration";
  /** AI finomítás: admin instrukció */
  instruction?: string;
  title: string;
  verse: string;
  content: string;
  prayer?: string;
  reflectionQuestion?: string;
  facebookCopy?: string;
  status?: string;
  promptVersion?: string;
}

export interface Devotional {
  /** Naptári nap (YYYY-MM-DD) — az áhítat egyetlen azonosítója (nincs napszámozás). */
  date: string;
  title: string;
  verse: string;
  content: string;
  prayer?: string;
  reflectionQuestion?: string;
  /** Napi áhítat illusztráció URL — üres, ha nincs hozzárendelve (Pexels / feltöltött) */
  imageUrl: string;
  /** Gemini által javasolt angol kulcsszavak Pexels kereséshez */
  imageKeywords?: string;
  /** Kép forrása: pexels_auto | pexels | manual | imagen */
  imageSource?: "pexels_auto" | "pexels" | "imagen" | "manual";
  /** Fotós neve / attribution (Pexels) */
  imageCredit?: string;
  imagePhotographerUrl?: string;
  pexelsPhotoId?: number;
  createdAt: string;
  generatedAt?: string;
  updatedAt?: string;
  status?: DevotionalStatus;
  /**
   * Heti sorozat azonosítója (a hét hétfője, YYYY-MM-DD). Csak a heti tervből
   * készült áhítat kapja. Ilyen áhítatnál a `approved` státusz azt jelenti:
   * „ütemezett” — a saját napján magától megjelenik; régi (heti azonosító nélküli)
   * rekordnál a nyilvánossághoz továbbra is `published` kell.
   */
  weekId?: string;
  promptVersion?: string;
  generationModel?: string;
  contentCharCount?: number;
  lastApiError?: string;
  editedByAdmin?: boolean;
  versionHistory?: DevotionalVersionSnapshot[];
  category?: string;
  facebookCopy?: string;
}

export interface GenerateRequestBody {
  date: string;
  verseText: string;
}

export interface GeneratedDevotionalContent {
  title: string;
  content: string;
}

/** Gemini dinamikus tervező teljes nap válasza */
export interface DynamicPlannedDay {
  title: string;
  verse: string;
  content: string;
  category: string;
  /** Rövid kivonat — Facebook megosztáshoz */
  excerpt?: string;
  facebookCopy?: string;
  imageKeywords?: string;
  /** false = félbeszakadt / hiányos — ne published */
  textComplete?: boolean;
  generationReviewMessage?: string;
  generationDiagnostics?: {
    sourceFunction: string;
    maxOutputTokens: number;
    finishReason: string;
    devotionalMarkdownLength: number;
    meditationLength: number;
    retryOccurred: boolean;
  };
}

/** Gemini AI finomítás preview / apply payload */
export interface DevotionalRefinementResult {
  title: string;
  verse: string;
  category: string;
  content: string;
  prayer?: string;
  reflectionQuestion?: string;
  facebookCopy?: string;
  imageKeywords?: string;
}

export interface AdminDailyGenerationJobSummary {
  date: string;
  status: "running" | "pending_retry" | "published" | "failed";
  retry_count: number;
  last_error: string | null;
  last_error_code: string | null;
  last_attempt_at: string | null;
  next_retry_at: string | null;
  published_at: string | null;
  phase: "initial" | "hourly";
  auto_retry_count: number;
}

/** Egy ellenőrzésre váró áhítat generálási figyelmeztetése — mindig dátummal és címmel. */
export interface AdminReviewWarning {
  date: string;
  title: string;
  message: string;
  /** A figyelmeztetés a mai áhítatra vonatkozik-e (különben másik napé). */
  isToday: boolean;
}

export interface AdminDevotionalContext {
  devReviewMode: boolean;
  autoGenerateDaily: boolean;
  autoPublishGenerated: boolean;
  cronEnabled: boolean;
  promptVersion: string;
  model: string;
  generationTarget: {
    action: string;
    date: string;
    blockedReason?: string;
  };
  /** Összefoglaló szöveg — a dátumot és a címet is tartalmazza. */
  reviewWarning?: string;
  /** Áhítatonkénti figyelmeztetések (dátum + cím + üzenet), újabb elöl. */
  reviewWarnings?: AdminReviewWarning[];
  /** A mai napot jóváhagyott heti terv kezeli: a napi automatikus generálás kihagyva. */
  weeklyPlanNotice?: { weekId: string; contentGap: boolean };
  /** Mai automatikus generálás állapota (cron + retry). */
  todayGenerationJob?: AdminDailyGenerationJobSummary | null;
  /** Külső cron retry endpoint — Hobby plan segítség (CRON_SECRET nélkül). */
  externalRetryCron?: {
    endpointUrl: string;
    scheduleLabel: string;
    helpText: string;
  };
}

